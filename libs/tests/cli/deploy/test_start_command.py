"""Choosing the start command for an MCP server deploy, without running anything."""

from pathlib import Path

import pytest
from arcade_cli.start_command import (
    FASTMCP_RUN_FLAGS,
    StartCommandError,
    find_server_objects,
    resolve_start_command,
)

FASTMCP_PROJECT = """
[project]
name = "srv"
version = "0.1.0"
dependencies = ["fastmcp>=2.14"]
"""

SDK_PROJECT = """
[project]
name = "srv"
version = "0.1.0"
dependencies = ["mcp>=1.20"]
"""

FASTMCP_SERVER = """
from fastmcp import FastMCP

mcp = FastMCP("srv")
"""

SDK1_HTTP_SERVER = """
from mcp.server.fastmcp import FastMCP

mcp = FastMCP("srv")

if __name__ == "__main__":
    mcp.run("streamable-http")
"""


def write(project: Path, files: dict[str, str]) -> Path:
    for name, content in files.items():
        path = project / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return project


class TestFlags:
    def test_every_fastmcp_run_gets_the_fixed_flags(self) -> None:
        assert FASTMCP_RUN_FLAGS == (
            "--transport",
            "http",
            "--host",
            "127.0.0.1",
            "--port",
            "8000",
            "--path",
            "/mcp",
            "--no-banner",
            "--skip-env",
        )


class TestExplicitCommand:
    def test_an_explicit_command_wins_over_detection(self, tmp_path: Path) -> None:
        write(tmp_path, {"pyproject.toml": FASTMCP_PROJECT, "fastmcp.json": "{}"})

        start = resolve_start_command(tmp_path, command="uvicorn app:app --workers 2")

        assert start.source == "command"
        assert start.command == "uvicorn app:app --workers 2"
        assert start.argv == ("uvicorn", "app:app", "--workers", "2")
        assert start.port is None
        assert start.path is None

    def test_a_blank_command_is_refused(self, tmp_path: Path) -> None:
        with pytest.raises(StartCommandError, match="`command` is empty"):
            resolve_start_command(tmp_path, command="  ")

    def test_path_is_kept_for_detection(self, tmp_path: Path) -> None:
        start = resolve_start_command(tmp_path, command="python app.py", path="/api/mcp")

        assert start.path == "/api/mcp"

    def test_a_path_without_a_leading_slash_is_refused(self, tmp_path: Path) -> None:
        with pytest.raises(StartCommandError, match="must start with '/'"):
            resolve_start_command(tmp_path, command="python app.py", path="api/mcp")


class TestFastMCPJson:
    def test_fastmcp_and_a_fastmcp_json_run_the_json(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {"pyproject.toml": FASTMCP_PROJECT, "fastmcp.json": "{}", "a.py": FASTMCP_SERVER},
        )

        start = resolve_start_command(tmp_path)

        assert start.source == "fastmcp.json"
        assert start.argv == ("fastmcp", "run", "fastmcp.json", *FASTMCP_RUN_FLAGS)
        assert start.port == 8000
        assert start.path == "/mcp"


class TestFastMCPRun:
    def test_the_single_server_object_is_run(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {"pyproject.toml": FASTMCP_PROJECT, "src/srv/server.py": FASTMCP_SERVER},
        )

        start = resolve_start_command(tmp_path)

        assert start.source == "fastmcp"
        assert start.argv == ("fastmcp", "run", "src/srv/server.py:mcp", *FASTMCP_RUN_FLAGS)
        assert start.command == (
            "fastmcp run src/srv/server.py:mcp --transport http --host 127.0.0.1 "
            "--port 8000 --path /mcp --no-banner --skip-env"
        )

    def test_fastmcp_declared_in_requirements_txt_counts(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {
                "requirements.txt": "# deps\n--index-url https://pypi.org/simple\nFastMCP[openai]==3.4.1\n",
                "server.py": FASTMCP_SERVER,
            },
        )

        assert resolve_start_command(tmp_path).source == "fastmcp"

    def test_requirements_included_with_r_count(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {
                "requirements.txt": "-r requirements/base.txt\n",
                "requirements/base.txt": "--requirement=extra.txt\n",
                "requirements/extra.txt": "fastmcp\n",
                "server.py": FASTMCP_SERVER,
            },
        )

        assert resolve_start_command(tmp_path).source == "fastmcp"

    def test_hashed_and_continued_requirements_count(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {
                "requirements.txt": (
                    "# generated by uv export\n"
                    "fastmcp==3.4.1 \\\n"
                    "    --hash=sha256:aaaa \\\n"
                    "    --hash=sha256:bbbb\n"
                    "httpx==0.28.1 --hash=sha256:cccc\n"
                ),
                "server.py": FASTMCP_SERVER,
            },
        )

        assert resolve_start_command(tmp_path).source == "fastmcp"

    def test_fastmcp_run_also_serves_an_sdk_object(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {
                "pyproject.toml": FASTMCP_PROJECT,
                "server.py": "from mcp.server.mcpserver import MCPServer\n\nserver = MCPServer('srv')\n",
            },
        )

        assert resolve_start_command(tmp_path).argv[2] == "server.py:server"

    def test_a_path_setting_is_passed_to_fastmcp_run(self, tmp_path: Path) -> None:
        write(tmp_path, {"pyproject.toml": FASTMCP_PROJECT, "server.py": FASTMCP_SERVER})

        start = resolve_start_command(tmp_path, path="/api/mcp")

        assert start.argv[start.argv.index("--path") + 1] == "/api/mcp"
        assert start.path == "/api/mcp"

    def test_several_server_objects_are_refused_and_listed(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {
                "pyproject.toml": FASTMCP_PROJECT,
                "a.py": FASTMCP_SERVER,
                "b.py": "import fastmcp\n\nother = fastmcp.FastMCP('b')\n",
            },
        )

        with pytest.raises(StartCommandError) as refusal:
            resolve_start_command(tmp_path)

        assert "a.py:mcp" in str(refusal.value)
        assert "b.py:other" in str(refusal.value)
        assert "`command`" in str(refusal.value)

    def test_no_server_object_is_refused(self, tmp_path: Path) -> None:
        write(tmp_path, {"pyproject.toml": FASTMCP_PROJECT, "server.py": "print('hi')\n"})

        with pytest.raises(StartCommandError, match="`command`"):
            resolve_start_command(tmp_path)


class TestFindServerObjects:
    def test_aliases_annotations_and_factories_are_found(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {
                "alias.py": "from fastmcp import FastMCP as F\n\na = F('a')\n",
                "annotated.py": "from fastmcp import FastMCP\n\nb: FastMCP = FastMCP('b')\n",
                "factory.py": "from fastmcp import FastMCP\n\nc = FastMCP.from_fastapi(app=None)\n",
                "module.py": "import mcp.server.fastmcp as fm\n\nd = fm.FastMCP('d')\n",
                "sdk1_public.py": "from mcp.server import FastMCP\n\ne = FastMCP('e')\n",
                "sdk2_public.py": "from mcp.server import MCPServer\n\nf = MCPServer('f')\n",
            },
        )

        found = {(obj.file.as_posix(), obj.name, obj.framework) for obj in find_server_objects(tmp_path)}

        assert found == {
            ("alias.py", "a", "fastmcp"),
            ("annotated.py", "b", "fastmcp"),
            ("factory.py", "c", "fastmcp"),
            ("module.py", "d", "mcp-sdk-1"),
            ("sdk1_public.py", "e", "mcp-sdk-1"),
            ("sdk2_public.py", "f", "mcp-sdk-2"),
        }

    def test_a_file_saved_with_a_byte_order_mark_is_read(self, tmp_path: Path) -> None:
        (tmp_path / "server.py").write_text(FASTMCP_SERVER, encoding="utf-8-sig")

        assert [obj.name for obj in find_server_objects(tmp_path)] == ["mcp"]

    def test_only_module_level_assignments_count(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {"factory.py": "from fastmcp import FastMCP\n\ndef make():\n    s = FastMCP('s')\n    return s\n"},
        )

        assert find_server_objects(tmp_path) == []

    def test_an_unrelated_class_named_fastmcp_does_not_count(self, tmp_path: Path) -> None:
        write(tmp_path, {"mine.py": "class FastMCP: ...\n\nx = FastMCP()\n"})

        assert find_server_objects(tmp_path) == []

    def test_tests_environments_and_unparsable_files_are_skipped(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {
                "server.py": FASTMCP_SERVER,
                "test_server.py": FASTMCP_SERVER,
                "server_test.py": FASTMCP_SERVER,
                "tests/helpers.py": FASTMCP_SERVER,
                "conftest.py": FASTMCP_SERVER,
                ".venv/lib/site.py": FASTMCP_SERVER,
                "venv/lib/site.py": FASTMCP_SERVER,
                "node_modules/x.py": FASTMCP_SERVER,
                "broken.py": "def (:\n",
            },
        )

        assert [obj.file.as_posix() for obj in find_server_objects(tmp_path)] == ["server.py"]


class TestMCPSDK:
    def test_sdk_1_script_runs_with_python(self, tmp_path: Path) -> None:
        write(tmp_path, {"pyproject.toml": SDK_PROJECT, "server.py": SDK1_HTTP_SERVER})

        start = resolve_start_command(tmp_path)

        assert start.source == "mcp-sdk"
        assert start.argv == ("python", "server.py")
        assert start.port is None
        assert start.path is None
        assert "fastmcp" not in start.command

    def test_sdk_2_script_runs_with_python(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {
                "pyproject.toml": SDK_PROJECT,
                "app/main.py": (
                    "from mcp.server.mcpserver import MCPServer\n\n"
                    "server = MCPServer('srv')\n\n"
                    "def main():\n"
                    "    server.run(transport='streamable-http', port=9000)\n\n"
                    "if __name__ == '__main__':\n"
                    "    main()\n"
                ),
            },
        )

        assert resolve_start_command(tmp_path).argv == ("python", "app/main.py")

    def test_run_on_a_server_imported_from_another_module(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {
                "pyproject.toml": SDK_PROJECT,
                "server.py": "from mcp.server.fastmcp import FastMCP\n\nmcp = FastMCP('srv')\n",
                "main.py": "from server import mcp\n\nmcp.run('streamable-http')\n",
            },
        )

        assert resolve_start_command(tmp_path).argv == ("python", "main.py")

    def test_a_same_named_object_from_another_module_is_not_the_server(
        self, tmp_path: Path
    ) -> None:
        write(
            tmp_path,
            {
                "pyproject.toml": SDK_PROJECT,
                "server.py": (
                    "from mcp.server.fastmcp import FastMCP\n\n"
                    "app = FastMCP('srv')\n"
                    "app.run('streamable-http')\n"
                ),
                "web.py": "from flask import app\n\napp.run('streamable-http')\n",
            },
        )

        assert resolve_start_command(tmp_path).argv == ("python", "server.py")

    def test_a_script_using_relative_imports_is_refused_with_a_suggestion(
        self, tmp_path: Path
    ) -> None:
        write(
            tmp_path,
            {
                "pyproject.toml": SDK_PROJECT,
                "src/pkg/__init__.py": "",
                "src/pkg/server.py": "from mcp.server.fastmcp import FastMCP\n\nmcp = FastMCP('srv')\n",
                "src/pkg/__main__.py": "from .server import mcp\n\nmcp.run('streamable-http')\n",
            },
        )

        with pytest.raises(StartCommandError) as refusal:
            resolve_start_command(tmp_path)

        assert "src/pkg/__main__.py uses relative imports" in str(refusal.value)
        assert 'command = "python -m src.pkg"' in str(refusal.value)

    @pytest.mark.parametrize("call", ["mcp.run()", "mcp.run('stdio')", "mcp.run(transport='stdio')"])
    def test_a_stdio_run_is_refused(self, tmp_path: Path, call: str) -> None:
        write(
            tmp_path,
            {
                "pyproject.toml": SDK_PROJECT,
                "server.py": f"from mcp.server.fastmcp import FastMCP\n\nmcp = FastMCP('srv')\n{call}\n",
            },
        )

        with pytest.raises(StartCommandError) as refusal:
            resolve_start_command(tmp_path)

        assert "stdio" in str(refusal.value)
        assert "server.py:4" in str(refusal.value)
        assert 'run("streamable-http")' in str(refusal.value)

    def test_an_sse_run_is_refused(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {
                "pyproject.toml": SDK_PROJECT,
                "server.py": "from mcp.server.fastmcp import FastMCP\n\nmcp = FastMCP('srv')\nmcp.run('sse')\n",
            },
        )

        with pytest.raises(StartCommandError, match="'sse'"):
            resolve_start_command(tmp_path)

    def test_a_transport_chosen_at_runtime_is_refused(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {
                "pyproject.toml": SDK_PROJECT,
                "server.py": (
                    "import sys\nfrom mcp.server.fastmcp import FastMCP\n\n"
                    "mcp = FastMCP('srv')\nmcp.run(sys.argv[1])\n"
                ),
            },
        )

        with pytest.raises(StartCommandError, match="`command`"):
            resolve_start_command(tmp_path)

    def test_several_http_scripts_are_refused_and_listed(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {"pyproject.toml": SDK_PROJECT, "one.py": SDK1_HTTP_SERVER, "two.py": SDK1_HTTP_SERVER},
        )

        with pytest.raises(StartCommandError) as refusal:
            resolve_start_command(tmp_path)

        assert "one.py" in str(refusal.value)
        assert "two.py" in str(refusal.value)

    def test_an_http_run_is_chosen_over_a_stdio_one(self, tmp_path: Path) -> None:
        write(
            tmp_path,
            {
                "pyproject.toml": SDK_PROJECT,
                "server.py": (
                    "import sys\nfrom mcp.server.fastmcp import FastMCP\n\nmcp = FastMCP('srv')\n"
                    "if '--stdio' in sys.argv:\n    mcp.run()\nelse:\n    mcp.run('streamable-http')\n"
                ),
            },
        )

        assert resolve_start_command(tmp_path).argv == ("python", "server.py")


